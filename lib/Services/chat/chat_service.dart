import 'package:firebase_database/firebase_database.dart';
import 'package:buildbuddy/Models/chat_room_model.dart';
import 'package:buildbuddy/Models/chat_user_model.dart';
import 'package:buildbuddy/Models/chat_message_model.dart';

class ChatService {
  final FirebaseDatabase _db = FirebaseDatabase.instance;

  // Method to create a chat room
  Future<void> createChatRoom(ChatUser currentUser, ChatUser otherUser) async {
    final chatRoom = ChatRoom(
      id: '', // Will be generated by Realtime Database automatically
      participants: [currentUser.uid, otherUser.uid],
      participantNames: [currentUser.name, otherUser.name],
      participantRoles: [currentUser.role, otherUser.role],
      lastMessage: '',
      lastMessageTime: DateTime.now().toString(),
      lastMessageSenderId: '',
      createdAt: DateTime.now().toString(),
    );

    // Create a new chat room in Firebase Realtime Database
    final chatRef = _db.ref().child('chatRooms').push();  // Generate unique ID for the chat room
    await chatRef.set(chatRoom.toMap());  // Save ChatRoom data to Firebase Realtime Database
  }

  // Method to send a message to a specific chat room
  Future<void> sendMessage(ChatMessage message, String chatRoomId) async {
    final chatMessagesRef = _db.ref()
        .child('chatRooms')
        .child(chatRoomId)
        .child('messages'); // Reference to messages subcollection

    await chatMessagesRef.push().set(message.toMap());  // Save message to the chat room
  }

  // Method to fetch all chat rooms for a user (either as participant or admin)
  Future<List<ChatRoom>> getChatRoomsForUser(String userId) async {
    final chatRoomsSnapshot = await _db.ref()
        .child('chatRooms')
        .orderByChild('participants')
        .equalTo(userId)
        .once();

    if (chatRoomsSnapshot.snapshot.value == null) {
      return [];
    }

    // Convert the snapshots to a list of ChatRoom objects
    final chatRoomsMap = chatRoomsSnapshot.snapshot.value as Map;
    return chatRoomsMap.entries.map((entry) {
      return ChatRoom.fromJson(Map<String, dynamic>.from(entry.value));
    }).toList();
  }

  // Method to fetch all messages in a specific chat room
  Future<List<ChatMessage>> getMessagesInChatRoom(String chatRoomId) async {
    final messagesSnapshot = await _db.ref()
        .child('chatRooms')
        .child(chatRoomId)
        .child('messages')
        .orderByChild('timestamp')
        .once();

    if (messagesSnapshot.snapshot.value == null) {
      return [];
    }

    // Convert the snapshots to a list of ChatMessage objects
    final messagesMap = messagesSnapshot.snapshot.value as Map;
    return messagesMap.entries.map((entry) {
      return ChatMessage.fromJson(Map<String, dynamic>.from(entry.value));
    }).toList();
  }

  // Method to fetch user details (by userId) from Firebase Realtime Database
  Future<ChatUser> getUserDetails(String userId) async {
    final userSnapshot = await _db.ref().child('users').child(userId).once();
    if (userSnapshot.snapshot.value != null) {
      return ChatUser.fromJson(Map<String, dynamic>.from(userSnapshot.snapshot.value as Map));
    } else {
      throw Exception('User not found');
    }
  }

  // Method to fetch all users in the chat room
  Future<List<ChatUser>> getParticipantsInChatRoom(String chatRoomId) async {
    final chatRoomSnapshot = await _db.ref().child('chatRooms').child(chatRoomId).once();
    if (chatRoomSnapshot.snapshot.value == null) {
      throw Exception('Chat room not found');
    }

    final chatRoom = ChatRoom.fromJson(Map<String, dynamic>.from(chatRoomSnapshot.snapshot.value as Map));
    final participants = chatRoom.participants;

    // Fetch user details for each participant
    final List<ChatUser> participantsDetails = [];
    for (var participantId in participants) {
      final user = await getUserDetails(participantId);
      participantsDetails.add(user);
    }
    return participantsDetails;
  }

  // Method to update the last message in a chat room
  Future<void> updateLastMessageInChatRoom(String chatRoomId, String message, String senderId) async {
    final chatRoomRef = _db.ref().child('chatRooms').child(chatRoomId);
    final chatRoomSnapshot = await chatRoomRef.once();

    if (chatRoomSnapshot.snapshot.value == null) {
      throw Exception('Chat room not found');
    }

    final chatRoom = ChatRoom.fromJson(Map<String, dynamic>.from(chatRoomSnapshot.snapshot.value as Map));
    final updatedChatRoom = chatRoom.copyWith(
      lastMessage: message,
      lastMessageTime: DateTime.now().toString(),
      lastMessageSenderId: senderId,
    );

    // Update the chat room document with the new last message details
    await chatRoomRef.update(updatedChatRoom.toMap());
  }
}

extension on ChatRoom {
  // Helper method to create a copy of a ChatRoom with updated fields
  ChatRoom copyWith({
    String? id,
    List<String>? participants,
    List<String>? participantNames,
    List<String>? participantRoles,
    String? lastMessage,
    String? lastMessageTime,
    String? lastMessageSenderId,
    String? createdAt,
  }) {
    return ChatRoom(
      id: id ?? this.id,
      participants: participants ?? this.participants,
      participantNames: participantNames ?? this.participantNames,
      participantRoles: participantRoles ?? this.participantRoles,
      lastMessage: lastMessage ?? this.lastMessage,
      lastMessageTime: lastMessageTime ?? this.lastMessageTime,
      lastMessageSenderId: lastMessageSenderId ?? this.lastMessageSenderId,
      createdAt: createdAt ?? this.createdAt,
    );
  }
}
