import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_database/firebase_database.dart';
import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:buildbuddy/Controllers/authControllers.dart';
import 'package:buildbuddy/Models/messageModel.dart';
import 'package:buildbuddy/Models/userModels.dart';
import 'dart:async';

/// Manages chat functionality for all stakeholders, specifically enabling chats between Homeowners
/// and Contractors based on stakeholderId. Aligns with SRS 3.2.2 (Usability), 3.2.1 (Performance),
/// 3.2.3 (Security), and 3.2.4 (Reliability).
class ChatController extends GetxController {
  final DatabaseReference _database = FirebaseDatabase.instance.ref();
  final FirebaseAuth _auth = FirebaseAuth.instance;
  final AuthController _authController = Get.find<AuthController>();

  final RxMap<String, List<Message>> _conversations = <String, List<Message>>{}.obs; // Key: homeownerId, Value: Messages
  final RxBool _isLoading = false.obs;
  final RxString _errorMessage = ''.obs;

  Map<String, List<Message>> get conversations => _conversations;
  bool get isLoading => _isLoading.value;
  String? get errorMessage => _errorMessage.value.isEmpty ? null : _errorMessage.value;

  StreamSubscription? _messagesSubscription;

  @override
  void onInit() {
    super.onInit();
    startRealTimeListeners(); // Call the public method on initialization
  }

  /// Starts real-time listeners for messages between the current stakeholder and Homeowners (for Contractors).
  void startRealTimeListeners() {
    final user = _auth.currentUser;
    if (user == null) {
      _errorMessage.value = 'User not authenticated';
      return;
    }

    _messagesSubscription = _database.child('messages/homeowner_contractor').onValue.listen((event) {
      if (event.snapshot.exists) {
        final data = event.snapshot.value as Map<dynamic, dynamic>?;
        if (data != null) {
          _conversations.clear();
          data.forEach((conversationKey, messages) {
            if (messages is Map) {
              final parts = conversationKey.split('_');
              if (parts.length == 2 && (parts.contains(user.uid))) {
                final otherUserId = parts.firstWhere((id) => id != user.uid);
                if (!_conversations.containsKey(otherUserId)) {
                  _conversations[otherUserId] = [];
                }
                messages.forEach((messageId, messageData) {
                  if (messageData is Map) {
                    final message = Message.fromMap(Map<String, dynamic>.from(messageData), id: messageId);
                    _conversations[otherUserId]!.add(message);
                  }
                });
                _conversations[otherUserId]!.sort((a, b) => b.timestamp.compareTo(a.timestamp)); // Newest first
              }
            }
          });
        }
      }
    }, onError: (error) {
      _errorMessage.value = 'Failed to load messages: $error';
      Get.snackbar('Error', 'Failed to load messages: $error',
          snackPosition: SnackPosition.BOTTOM, backgroundColor: Colors.red);
    });
  }

  void _stopRealTimeListeners() {
    _messagesSubscription?.cancel();
    _conversations.clear();
  }

  /// Sends a message to a specific Homeowner from a Contractor.
  Future<void> sendMessageToHomeowner(String homeownerId, String content) async {
    _isLoading.value = true;
    try {
      final user = _auth.currentUser;
      if (user == null) {
        _errorMessage.value = 'User not authenticated';
        return;
      }

      if (!_isValidHomeowner(homeownerId)) {
        _errorMessage.value = 'Invalid Homeowner ID';
        return;
      }

      final message = Message(
        id: '', // Will be generated by Firebase
        senderId: user.uid,
        receiverId: homeownerId,
        content: content,
        timestamp: DateTime.now(),
        type: 'homeowner_contractor',
      );

      final conversationKey = _getConversationKey(user.uid, homeownerId);
      final messageRef = _database.child('messages/homeowner_contractor/$conversationKey').push();
      await messageRef.set(message.toJson());
    } catch (e) {
      _errorMessage.value = 'Failed to send message to homeowner: $e';
      Get.snackbar('Error', 'Failed to send message to homeowner: $e',
          snackPosition: SnackPosition.BOTTOM, backgroundColor: Colors.red);
    } finally {
      _isLoading.value = false;
    }
  }

  /// Helper method to validate if the homeownerId exists (simplified for now).
  bool _isValidHomeowner(String homeownerId) {
    final homeowners = _authController.users.where((user) => user.role == UserRole.homeowner).toList();
    return homeowners.any((user) => user.uid == homeownerId);
  }

  /// Generates a unique conversation key for the Contractor-Homeowner pair.
  String _getConversationKey(String senderId, String receiverId) {
    final ids = [senderId, receiverId]..sort(); // Sort the list
    return ids.join('_'); // Join with underscore to return a String
  }

  /// Cleans up resources, ensuring reliability (SRS 3.2.4).
  @override
  void onClose() {
    _stopRealTimeListeners();
    super.onClose();
  }
}